import { stat } from 'node:fs/promises';
import { join } from 'node:path';
import { listDir, splitDirs } from '../../ingest/discover';
import { finalize, GIT_COMMIT, jsonLines, newRaw, noteCacheWriteTtl, noteContext, noteCwd, noteEffort, noteTs, type RawSession } from '../../ingest/normalize';
import type { SessionRecord } from '../../ingest/types';
import type { ReadOptions, ReadResult, SessionReader, DoctorEnv } from '../types';

/**
 * Claude Code transcript reader. Reads session files at depth one under each
 * project directory; never the subagents folders. Extracts timestamps, entry
 * kinds, cwd, tool-call names and git commit calls. No prompt text.
 */
const PROVIDER = 'anthropic-claude-code';

/** The model name the transcript writes when a record stands in for a reply that never came. */
const SYNTHETIC = '<synthetic>';

/** Slash-command scaffolding and shell echoes that the transcript stores as user lines. */
const COMMAND_MARKER = /^<(command-name|command-message|command-args|local-command-stdout|local-command-stderr|bash-input|bash-stdout|bash-stderr)>/;
const CAVEAT_MARKER = /^Caveat: The messages below were generated by the user while running local commands/;

/**
 * A person taking a turn, not the transcript echoing itself. Where `origin` is present it
 * settles the question. Where it is absent, a string body is a turn unless it is command
 * scaffolding or the injected caveat, and a block array is a turn only when it carries
 * something the person wrote or attached rather than a tool result.
 */
function isHumanTurn(d: Record<string, unknown>): boolean {
  if (d['isSidechain'] === true || d['isCompactSummary'] === true || d['isMeta'] === true) return false;
  const origin = d['origin'] as { kind?: string } | undefined;
  if (origin && typeof origin === 'object') return origin.kind === 'human';
  const content = (d['message'] as { content?: unknown } | undefined)?.content;
  if (typeof content === 'string') {
    const text = content.trim();
    return text.length > 0 && !COMMAND_MARKER.test(text) && !CAVEAT_MARKER.test(text);
  }
  if (Array.isArray(content)) {
    return (content as Array<Record<string, unknown>>).some((b) => b['type'] === 'text' || b['type'] === 'image');
  }
  return false;
}

function scanLine(raw: RawSession, d: Record<string, unknown>): void {
  noteTs(raw, d['timestamp']);
  noteCwd(raw, d['cwd']);
  if (typeof d['version'] === 'string' && !raw.toolVersion) raw.toolVersion = d['version'];
  // Effort sits beside cwd and version on the record, not inside message, so it is read before
  // the assistant narrowing rather than after it. Sidechains are excluded: a subagent's effort
  // is the subagent's, and letting it through would attribute it to the session that spawned it.
  if (d['isSidechain'] !== true) noteEffort(raw, d['effort']);
  const type = d['type'];
  if (type === 'user') {
    if (isHumanTurn(d)) raw.humanTurns += 1;
    return;
  }
  if (type !== 'assistant' || d['isSidechain'] === true) return;
  const message = d['message'] as { id?: unknown; model?: unknown; content?: unknown } | undefined;
  if (!message) return;
  // The transcript names the model SYNTHETIC when the record is not a reply from one: an
  // API error carrying isApiErrorMessage, or a "No response requested." placeholder. Both
  // carry a real message id and zeroed usage, so counting them inflates assistantMessages
  // and puts a model in the record that no vendor ever billed for.
  if (message.model === SYNTHETIC) return;
  if (typeof message.id === 'string') raw.assistantIds.add(message.id);
  if (typeof message.model === 'string') raw.models.add(message.model);
  // What the model read to produce this reply: cache it re-read, cache it wrote, and fresh
  // input. Claude states no context window, so contextWindowTokens stays null.
  const u = (message as { usage?: Record<string, unknown> }).usage;
  if (u) {
    const part = (k: string): number => (typeof u[k] === 'number' ? (u[k] as number) : 0);
    noteContext(raw, part('cache_read_input_tokens') + part('cache_creation_input_tokens') + part('input_tokens'));
    const cc = u['cache_creation'] as Record<string, unknown> | undefined;
    if (cc) noteCacheWriteTtl(raw, cc['ephemeral_1h_input_tokens'], cc['ephemeral_5m_input_tokens']);
  }
  if (!Array.isArray(message.content)) return;
  for (const block of message.content as Array<Record<string, unknown>>) {
    if (block['type'] !== 'tool_use') continue;
    raw.toolCalls += 1;
    const input = block['input'] as { command?: unknown } | undefined;
    if (typeof input?.command === 'string' && GIT_COMMIT.test(input.command)) raw.commitCommands += 1;
  }
}

export async function readClaudeSession(file: string, sessionId: string, idleGapMinutes: number): Promise<SessionRecord | null> {
  const raw = newRaw(PROVIDER, sessionId);
  for await (const d of jsonLines(file)) scanLine(raw, d);
  return finalize(raw, idleGapMinutes);
}

export const claudeReader: SessionReader = {
  verifiedAgainst: '2.1.261',
  providesUtilization: false,
  async read(opts: ReadOptions, env: DoctorEnv): Promise<ReadResult> {
    const sinceMs = Date.parse(`${opts.since}T00:00:00Z`);
    const untilMs = Date.parse(`${opts.until}T23:59:59.999Z`);
    const sessions: SessionRecord[] = [];
    let filesRead = 0;
    for (const root of splitDirs(env.env['CLAUDE_CONFIG_DIR'], join(env.home, '.claude'))) {
      const projects = join(root, 'projects');
      const dirs = await listDir(projects);
      if (!dirs) continue;
      for (const dir of dirs) {
        const listed = await listDir(join(projects, dir));
        if (!listed) continue;
        for (const f of listed.filter((x) => x.endsWith('.jsonl'))) {
          const file = join(projects, dir, f);
          const s = await stat(file);
          // a file last written before the window cannot hold a session ending inside it
          if (s.mtimeMs < sinceMs) continue;
          filesRead += 1;
          const rec = await readClaudeSession(file, f.slice(0, -6), opts.idleGapMinutes);
          if (rec && Date.parse(rec.lastTs) >= sinceMs && Date.parse(rec.lastTs) <= untilMs) sessions.push(rec);
        }
      }
    }
    return { sessions, utilization: [], filesRead };
  },
};
